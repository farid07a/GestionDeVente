    public void setVersementSpecialInTab(Entreprise entreprise) {        
        DefaultTableModel model = (DefaultTableModel) tab.getModel();
        model.setRowCount(0);
        List< VersementEntreprise> versementEntreprises = versementEntrepriseDAOImpl.getAllVersementSpecialeByEntreprise(entreprise);
        int row = versementEntreprises.size();
        double TotalVersement = 0.0;
        double TotaleAchat = 0.0;
        for (VersementEntreprise versementEntreprise : versementEntreprises) {
            model.insertRow(0, new Object[]{versementEntreprise.getId(),
                versementEntreprise.getDate_versement(),
                versementEntreprise.getMode_paiement(),
                versementEntrepriseDAOImpl.getEtat (versementEntreprise),
                formatter.format(versementEntreprise.getReste_credit()),
                formatter.format(versementEntreprise.getTotal_credit()),
                formatter.format(versementEntreprise.getMontant()),
                versementEntreprise.getEntreprise().getNom_ar(),
                (row < 10) ? "0" + row : row        
            });
            row--;
            TotalVersement = TotalVersement + versementEntreprise.getMontant();
            TotaleAchat = TotaleAchat + versementEntreprise.getTotal_credit();
            labCredit.setText(formatter.format(versementEntreprise.getReste_credit()));
        }
        LabSomVersemEntrep.setText(formatter.format(TotalVersement));
        
    }


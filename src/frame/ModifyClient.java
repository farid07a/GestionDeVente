    public void setInfoClient() {
        txt_matricul.setText(client.getMatricule());
        nom.setText(client.getNom());
        prenom.setText(client.getPrenom());
        tel.setText(client.getTel());
        adress.setText(client.getAdresse());
        if (client.getEntreprise() != null) {
            com_entrep.setSelectedItem(client.getEntreprise().getNom_ar());
        } else {
            com_entrep.setSelectedIndex(-1);
        }

    }

    public void setInfoEntrepriseOnCombox() {
        List<Entreprise> entreprises = new EntrepriseDAOImpl(connection).findAll();

        for (Entreprise entreprise : entreprises) {
            com_entrep.addItem(entreprise.getNom_ar());
        }
    }


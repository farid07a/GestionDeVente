    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        if (nom.getText().isEmpty() || prenom.getText().isEmpty()) {
            new Exite(this, homeForm).showMessage("خــطـأ", "تأكد من ادخال المـعلـومـات");
            return;
        }

        Entreprise entreprise = null;
        if (com_entrep.getSelectedIndex() != -1) {
            String nomEntreprise = com_entrep.getSelectedItem().toString();
            entreprise = new EntrepriseDAOImpl(connection).getEntrepriseParName(nomEntreprise);
        }

        client.setNom(nom.getText());
        client.setPrenom(prenom.getText());
        client.setMatricule(txt_matricul.getText());
        client.setTel(tel.getText());
        client.setAdresse(adress.getText());
        client.setEntreprise(entreprise);

        if (new ClientDAOImpl(connection).update(client) > 0) {
            this.dispose();
            new ValidationMessageDialog(this, homeForm).showMessage("تأكيد", "نم تعديل معلومات الزبون بنجاح ");
            homeForm.getPan_client().setClientsOnTab();

        }
    }//GEN-LAST:event_btnSaveActionPerformed


    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        if (txt_nomfr.getText().isEmpty() ||  txt_nom.getText().isEmpty()){
            new Exite(this, homeForm).showMessage("خــطـأ", "تأكد من ادخال المـعلـومـات");
        return;
        }
        CategorieDAOImpl categorieDAOImpl = new CategorieDAOImpl(connection);
        Categorie categorie = new Categorie(0, txt_nom.getText(),txt_nomfr.getText() );
        
        if( categorieDAOImpl.save(categorie) >0){
            this.dispose();
            new ValidationMessageDialog(this, homeForm).showMessage("تأكيد", "تم إضافةالـنـوعـيـة بنجاح ");
            this.homeForm.getPan_categorie().setCategoriesOnTab();

        }
    }//GEN-LAST:event_btnSaveActionPerformed


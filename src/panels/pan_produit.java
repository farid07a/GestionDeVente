    public void setProduitsOnTab() {
        DefaultTableModel model = (DefaultTableModel) tab.getModel();
        model.setRowCount(0);
        List<Produit> produits = produitDAOImpl.findAll();
        String marque = "";
        for (Produit produit : produits) {
            int id = produit.getId();
            String refernce = produit.getReference();
            String desg = produit.getDesignation();
            Categorie categorie = produit.getCategorie();

            if (categorie != null) {
                marque = categorie.getNomCategorie();
            }
            double prix_ache = produit.getPrix_achat();
            double prix_vent = produit.getPrix_vente();
            int qt = produit.getQty();
            model.insertRow(0, new Object[]{id,
                formatter.format(prix_vent),
                formatter.format(prix_ache),
                qt, refernce, marque,
                marque, desg});
//            model.addRow(new Object[]{id, prix_vent, prix_ache, qt, refernce, marque,
//                marque, desg});
        }

        lab_nbProduit.setText(produits.size() + "");

    }

